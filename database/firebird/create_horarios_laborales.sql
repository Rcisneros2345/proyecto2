CREATE TABLE HORARIOS_LABORALES (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NUMEMPLEADO VARCHAR(50) NOT NULL,
    DIA_SEMANA SMALLINT NOT NULL CHECK (DIA_SEMANA BETWEEN 1 AND 7),
    HORA_ENTRADA TIME NOT NULL,
    HORA_SALIDA TIME NOT NULL,
    HORA_SALIDA_COMER TIME,
    HORA_REGRESO_COMER TIME,
    ACTIVO INTEGER DEFAULT 1,
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FECHA_ACTUALIZACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Índice único para evitar duplicados por empleado y día
CREATE UNIQUE INDEX UK_HORARIOS_LABORALES_EMP_DIA 
    ON HORARIOS_LABORALES (NUMEMPLEADO, DIA_SEMANA);

-- Comentarios
COMMENT ON TABLE HORARIOS_LABORALES IS 'Horarios laborales de empleados por día de la semana';
COMMENT ON COLUMN HORARIOS_LABORALES.NUMEMPLEADO IS 'Número de empleado (FK a EMPLEADOS.NUMEMPLEADO)';
COMMENT ON COLUMN HORARIOS_LABORALES.DIA_SEMANA IS '1=Lunes, 2=Martes, 3=Miércoles, 4=Jueves, 5=Viernes, 6=Sábado, 7=Domingo';
COMMENT ON COLUMN HORARIOS_LABORALES.HORA_ENTRADA IS 'Hora de entrada laboral';
COMMENT ON COLUMN HORARIOS_LABORALES.HORA_SALIDA IS 'Hora de salida laboral';
COMMENT ON COLUMN HORARIOS_LABORALES.HORA_SALIDA_COMER IS 'Hora de salida a comer (opcional)';
COMMENT ON COLUMN HORARIOS_LABORALES.HORA_REGRESO_COMER IS 'Hora de regreso de comer (opcional)';
COMMENT ON COLUMN HORARIOS_LABORALES.ACTIVO IS '1=Activo, 0=Inactivo';

